"""Rebuild a compiler-resolved inventory of the production mod's public game API references."""
import argparse
import json
import os
from pathlib import Path
import subprocess

ROOT=Path(__file__).parent

def audit(game_dir: Path):
    jar=game_dir/'SongsOfSyx.jar'
    sources=game_dir/'info/SongsOfSyx-sources.jar'
    if not jar.is_file() or not sources.is_file():
        raise SystemExit('The licensed game JAR and shipped source archive are required')
    java=['java']
    if os.environ.get('SYX_JAVA_HOME'):java+=['-Djava.home='+os.environ['SYX_JAVA_HOME']]
    out=ROOT/'build/audit';out.mkdir(parents=True,exist_ok=True)
    subprocess.run([*java,'-m','jdk.compiler/com.sun.tools.javac.Main','--release','17','-d',str(out),
        str(ROOT/'dev/ApiAudit.java'),str(ROOT/'mod/src/main/java/syx/assistant/JsonWriter.java')],check=True)
    subprocess.run([*java,'-cp',str(out),'syx.dev.ApiAudit',str(jar),str(ROOT/'mod/src/main/java'),
        str(sources),str(ROOT/'api-audit.json')],check=True)
    manifest=json.loads((ROOT/'api-audit.json').read_text())
    if any(not member['public'] for member in manifest['members']):
        raise SystemExit('Non-public game reference found; audit failed')
    gaps=[m['id'] for m in manifest['members'] if not m['compiler_generated_enum'] and len(m['source_candidates'])!=1]
    if gaps:raise SystemExit('Missing/ambiguous source anchors: '+str(gaps))
    from dev.verify_bytecode import verify
    manifest['binary_checks']=verify(java,jar)
    (ROOT/'api-audit.json').write_text(json.dumps(manifest,indent=2)+'\n')
    (ROOT/'syx_api_manifest.py').write_text('# Generated by audit_api.py; metadata only, no game source or values.\nMANIFEST = '+repr(manifest)+'\n')
    return manifest

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--game-dir',type=Path,required=True)
    audit(p.parse_args().game_dir)
